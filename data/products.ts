import type {
  Aesthetic,
  ColorFamily,
  FitPreference,
  Occasion,
  Product,
  ProductCategory,
  ProductVisualType,
  StylePreference,
} from "@/types";

const apparelCore = ["XS", "S", "M", "L", "XL"];
const apparelExtended = ["XS", "S", "M", "L", "XL", "XXL"];
const outerwearSizes = ["S", "M", "L", "XL"];
const shoeRun = ["6", "7", "8", "9", "10", "11", "12"];
const oneSize = ["One Size"];

const allStyles: StylePreference[] = [
  "feminine",
  "masculine",
  "androgynous",
  "mixed / open to all",
];

type ProductSeed = {
  category: ProductCategory;
  name: string;
  store: string;
  price: number;
  colors: string[];
  primaryColor: string;
  colorFamily: ColorFamily;
  fitType: FitPreference;
  styleNotes: string;
  visualType: ProductVisualType;
  stylePreferences?: StylePreference[];
  extraAesthetics?: Aesthetic[];
  extraOccasions?: Occasion[];
};

type BundleSeed = {
  id: string;
  baseAesthetics: Aesthetic[];
  baseOccasions: Occasion[];
  items: ProductSeed[];
};

function slugify(value: string) {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function defaultSizes(category: ProductCategory) {
  if (category === "shoes") {
    return shoeRun;
  }

  if (category === "accessory") {
    return oneSize;
  }

  if (category === "outerwear") {
    return outerwearSizes;
  }

  return category === "top" ? apparelExtended : apparelCore;
}

function buildBundle(seed: BundleSeed) {
  return seed.items.map((item) => {
    const id = `${seed.id}-${slugify(item.name)}`;

    return {
      id,
      name: item.name,
      brand: item.store,
      store: item.store,
      category: item.category,
      price: item.price,
      aestheticTags: [...new Set([...seed.baseAesthetics, ...(item.extraAesthetics ?? [])])],
      occasionTags: [...new Set([...seed.baseOccasions, ...(item.extraOccasions ?? [])])],
      colors: item.colors,
      primaryColor: item.primaryColor,
      colorFamily: item.colorFamily,
      availableSizes: defaultSizes(item.category),
      fitType: item.fitType,
      stylePreferences: item.stylePreferences ?? allStyles,
      styleNotes: item.styleNotes,
      image: `mock-${seed.id}-${item.category}`,
      visualType: item.visualType,
      url: `/mock-products/${seed.id}/${item.category}`,
      affiliateReady: true,
    } satisfies Product;
  });
}

